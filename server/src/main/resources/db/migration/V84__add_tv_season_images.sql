CREATE TABLE tv_season_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    show_id BIGINT NOT NULL REFERENCES tv_shows(id) ON DELETE CASCADE,
    season_number INTEGER NOT NULL CHECK (season_number >= 0),
    url TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (show_id, season_number, url)
);

INSERT INTO tv_season_images(show_id, season_number, url)
SELECT show_id, season_number, cover_url FROM tv_season_covers;
