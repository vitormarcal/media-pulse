ALTER TABLE books ADD COLUMN hardcover_id BIGINT;
CREATE INDEX idx_books_hardcover_id ON books(hardcover_id) WHERE hardcover_id IS NOT NULL;

CREATE TABLE book_series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    hardcover_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE book_universes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE book_series_items (
    series_id BIGINT NOT NULL REFERENCES book_series(id) ON DELETE CASCADE,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position > 0),
    PRIMARY KEY (series_id, book_id)
);
CREATE INDEX idx_book_series_items_book ON book_series_items(book_id);
CREATE TABLE book_universe_series (
    universe_id BIGINT NOT NULL REFERENCES book_universes(id) ON DELETE CASCADE,
    series_id BIGINT NOT NULL REFERENCES book_series(id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position > 0),
    PRIMARY KEY (universe_id, series_id)
);
CREATE INDEX idx_book_universe_series_series ON book_universe_series(series_id);
